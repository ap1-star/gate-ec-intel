import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const context={window:{}};
vm.runInNewContext(readFileSync('dist/v5-math.js','utf8'),context);
const {leaveOneYearOut}=context.window.V5Math;
const vectors=[[20,80],[30,70],[40,60],[50,50]];
const result=leaveOneYearOut(vectors,[2019,2020,2021,2022],'recent');
assert.equal(result.rows.length,4);
assert.deepEqual(Array.from(result.rows[0].trainYears),[2020,2021,2022]);
assert.equal(result.rows[0].baseline[0],40);
assert.equal(result.rows[0].estimate[0],(30+40*2+50*3)/6);
assert.equal(result.rows[0].observed[0],20);
assert.equal(result.fullMean[0],35);
assert.equal(result.summary.yearCount,4);
assert.equal(result.summary.subjects,2);
const equal=leaveOneYearOut(vectors,[2019,2020,2021,2022],'equal');
assert.ok(Math.abs(equal.summary.modelMae-equal.summary.baselineMae)<1e-10);
assert.equal(equal.summary.beatsBaseline,false);
const constant=leaveOneYearOut([[15,85],[15,85],[15,85]],[1,2,3]);
assert.equal(constant.summary.modelMae,0);
assert.equal(constant.summary.beatsBaseline,false);
assert.throws(()=>leaveOneYearOut([[20,80],[40]],[1,2]));
const subjects=['Analog Circuits','Engineering Mathematics','General Aptitude'];
const stable=[[65,20,15],[60,25,15],[70,15,15]];
const projection=context.window.V5Math.ec2027MeanForecast(stable,subjects);
assert.equal(projection.forecast.reduce((a,b)=>a+b,0),100);
assert.equal(projection.forecast[1],13);
assert.equal(projection.forecast[2],15);
assert.equal(projection.forecast[0],72);
assert.throws(()=>context.window.V5Math.ec2027MeanForecast(stable,['Analog Circuits','Math','General Aptitude']));
console.log('PASS leave-one-year-out: holdout isolation, baseline, recency, equal-control, zero-error and validation');
